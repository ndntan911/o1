// Command copilot-eval runs the copilot evaluation fixtures against a
// configured model provider and writes a markdown report.
//
// It is opt-in and never part of the build: without O1_AI_PROVIDER it exits 2
// and writes nothing. A stub run exercises the harness but is not evidence of
// model quality; the report says so.
package main

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"strings"
	"time"

	"o1/internal/ai"
	"o1/internal/copilot"
)

func main() {
	os.Exit(run(os.Args[1:], os.Stdout, os.Stderr))
}

func run(args []string, stdout, stderr io.Writer) int {
	flags := flag.NewFlagSet("copilot-eval", flag.ContinueOnError)
	flags.SetOutput(stderr)
	fixturesDir := flags.String("fixtures", "internal/copilot/testdata/eval", "directory of *.json fixtures")
	outPath := flags.String("out", "../docs/ai/copilot-eval.md", "markdown report to write")
	if err := flags.Parse(args); err != nil {
		return 2
	}

	providerName := strings.ToLower(strings.TrimSpace(os.Getenv("O1_AI_PROVIDER")))
	if providerName == "" || providerName == ai.ProviderOff {
		fmt.Fprintln(stderr, "copilot-eval: O1_AI_PROVIDER is off; set it to openai (or another tool provider) to run the evaluation")
		return 2
	}

	timeout := 30 * time.Second
	if raw := strings.TrimSpace(os.Getenv("O1_AI_TIMEOUT")); raw != "" {
		parsed, err := time.ParseDuration(raw)
		if err != nil {
			fmt.Fprintf(stderr, "copilot-eval: invalid O1_AI_TIMEOUT %q: %v\n", raw, err)
			return 2
		}
		timeout = parsed
	}
	headers, err := parseHeaders(os.Getenv("O1_AI_EXTRA_HEADERS"))
	if err != nil {
		fmt.Fprintf(stderr, "copilot-eval: %v\n", err)
		return 2
	}

	model := strings.TrimSpace(os.Getenv("O1_COPILOT_MODEL"))
	if model == "" {
		model = strings.TrimSpace(os.Getenv("O1_AI_MODEL"))
	}
	if model == "" {
		if providerName != ai.ProviderStub {
			fmt.Fprintln(stderr, "copilot-eval: O1_COPILOT_MODEL or O1_AI_MODEL is required")
			return 2
		}
		model = providerName
	}

	provider, err := ai.New(ai.Settings{
		Provider: providerName,
		BaseURL:  strings.TrimSpace(os.Getenv("O1_AI_BASE_URL")),
		APIKey:   strings.TrimSpace(os.Getenv("O1_AI_API_KEY")),
		Model:    model,
		Timeout:  timeout,
		Headers:  headers,
	})
	switch {
	case errors.Is(err, ai.ErrNotConfigured):
		fmt.Fprintf(stderr, "copilot-eval: provider %q is not configured: %v\n", providerName, err)
		return 2
	case err != nil:
		fmt.Fprintf(stderr, "copilot-eval: build provider: %v\n", err)
		return 2
	case provider == nil:
		fmt.Fprintf(stderr, "copilot-eval: provider %q is off\n", providerName)
		return 2
	}
	toolProvider, ok := provider.(ai.ToolProvider)
	if !ok {
		fmt.Fprintf(stderr, "copilot-eval: provider %q does not support tool calls\n", providerName)
		return 2
	}

	fixtures, err := copilot.LoadFixtures(*fixturesDir)
	if err != nil {
		fmt.Fprintf(stderr, "copilot-eval: %v\n", err)
		return 1
	}

	results, err := copilot.RunLive(context.Background(), toolProvider, fixtures, model)
	if err != nil {
		fmt.Fprintf(stderr, "copilot-eval: %v\n", err)
		return 1
	}

	report := renderReport(providerName, model, results)
	if err := os.WriteFile(*outPath, []byte(report), 0o644); err != nil {
		fmt.Fprintf(stderr, "copilot-eval: write report: %v\n", err)
		return 1
	}

	passed := 0
	for _, result := range results {
		if result.Passed {
			passed++
		}
	}
	fmt.Fprintf(stdout, "wrote %s: %d/%d fixtures passed\n", *outPath, passed, len(results))
	return 0
}

// parseHeaders accepts the same comma-separated name=value list as
// O1_AI_EXTRA_HEADERS in the service configuration.
func parseHeaders(raw string) (map[string]string, error) {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return nil, nil
	}
	headers := make(map[string]string)
	for _, pair := range strings.Split(raw, ",") {
		pair = strings.TrimSpace(pair)
		if pair == "" {
			return nil, errors.New("invalid O1_AI_EXTRA_HEADERS: empty header pair")
		}
		name, value, ok := strings.Cut(pair, "=")
		if !ok {
			return nil, errors.New("invalid O1_AI_EXTRA_HEADERS: header pair missing '='")
		}
		name = strings.TrimSpace(name)
		value = strings.TrimSpace(value)
		if name == "" || value == "" {
			return nil, errors.New("invalid O1_AI_EXTRA_HEADERS: header name and value must be non-empty")
		}
		headers[name] = value
	}
	return headers, nil
}

// renderReport writes the table and the caveats that make it honest. A
// non-openai provider is stub-like, so its rows measure the fixtures and the
// harness, not a model.
func renderReport(providerName, model string, results []copilot.EvalResult) string {
	var report strings.Builder
	generated := time.Now().UTC().Format(time.RFC3339)

	report.WriteString("# Copilot evaluation\n\n")
	fmt.Fprintf(&report, "Generated by `make copilot-eval` on %s with provider `%s` and model `%s`.\n\n", generated, providerName, model)

	if providerName != ai.ProviderOpenAI {
		fmt.Fprintf(&report, "> **Stub-only run.** `O1_AI_PROVIDER` was `%s`, so this table records the fixtures and the harness, not a model. Stub-only results are not evidence of model quality. Set `O1_AI_PROVIDER=openai`, `O1_AI_API_KEY`, and `O1_AI_MODEL`, then rerun `make copilot-eval` to record a live run.\n\n", providerName)
	} else {
		report.WriteString("> The rows below are one live run. Model answers vary; rerun before drawing a conclusion.\n\n")
	}

	report.WriteString("| Fixture | Result | Status | Tool calls | Input tokens | Output tokens | Unsupported citations |\n")
	report.WriteString("|---|---|---|---:|---:|---:|---:|\n")
	passed := 0
	for _, result := range results {
		verdict := "fail"
		if result.Passed {
			verdict = "pass"
			passed++
		}
		fmt.Fprintf(&report, "| %s | %s | %s | %d | %d | %d | %d |\n",
			result.Fixture, verdict, result.Status, result.ToolCalls,
			result.InputTokens, result.OutputTokens, result.UnsupportedCitations)
	}
	fmt.Fprintf(&report, "\n**Pass rate: %d/%d.**\n\n", passed, len(results))

	report.WriteString("## What a pass means\n\n")
	report.WriteString("Each fixture fixes the redacted seed and the tool results, then asserts named\n")
	report.WriteString("properties against the run: that the agent called `o1_get_recent_checks`, cited a\n")
	report.WriteString("failure class or a successful check, refused when the data was insufficient, stayed\n")
	report.WriteString("inside the caps, did not leave the read-only tool allowlist, or saw a truncated\n")
	report.WriteString("result. The check never compares prose, so different wording passes.\n\n")
	report.WriteString("\"Unsupported citations\" counts the evidence items the model claimed that the server\n")
	report.WriteString("dropped because the tool call id did not exist or the pointed value did not match.\n")

	if passed < len(results) {
		report.WriteString("\n## Failures\n\n")
		for _, result := range results {
			if result.Passed {
				continue
			}
			reason := strings.ReplaceAll(strings.TrimSpace(result.Failure), "\n", "; ")
			fmt.Fprintf(&report, "- `%s`: %s\n", result.Fixture, reason)
		}
	}

	return report.String()
}
